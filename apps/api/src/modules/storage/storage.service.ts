import { Injectable } from '@nestjs/common';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import { env } from '../../config/env.js';

/**
 * Storage abstraction. The prototype stores files on local disk; an S3-compatible adapter
 * (Cloudflare R2 etc.) can implement the same interface later without touching callers.
 */
export interface StorageProvider {
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
}

@Injectable()
export class LocalDiskStorage implements StorageProvider {
  private readonly root = resolve(env().STORAGE_DIR, 'objects');

  private pathFor(key: string): string {
    const full = resolve(this.root, key);
    // Keys are generated by the server, but guard against path traversal anyway.
    if (!full.startsWith(this.root + sep)) throw new Error('Invalid storage key');
    return full;
  }

  async put(key: string, data: Buffer, _contentType?: string): Promise<void> {
    const path = this.pathFor(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, data);
  }

  async get(key: string): Promise<Buffer> {
    return readFile(this.pathFor(key));
  }

  async delete(key: string): Promise<void> {
    await rm(this.pathFor(key), { force: true });
  }
}
